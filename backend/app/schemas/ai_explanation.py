"""Pydantic schemas for Phase 13: LLM / AI Explanation Layer.

Provides structured data models for AI explanation results, requests, and responses.
All AI explanations are strict natural-language translations of deterministic calculations.
"""

from __future__ import annotations

from enum import Enum
from typing import List, Optional

from pydantic import BaseModel, Field

from app.schemas.decision import DecisionAnalyzeRequest, DecisionAnalyzeResponse


class AIExplanationStatus(str, Enum):
    """Status of the AI explanation generation."""

    SUCCESS = "success"
    FALLBACK_DISABLED = "fallback_disabled"
    FALLBACK_PROVIDER_ERROR = "fallback_provider_error"
    FALLBACK_VALIDATION_FAILED = "fallback_validation_failed"
    FALLBACK_TIMEOUT = "fallback_timeout"


class AIExplanationResult(BaseModel):
    """Structured, validated natural-language explanation generated by the LLM."""

    summary: str = Field(
        description="High-level narrative summary explaining the scenario's deterministic impact."
    )
    cash_flow_impact_narrative: str = Field(
        description="Clear narrative explaining cash flow movement, distinguishing one-time vs recurring impacts."
    )
    liquidity_narrative: str = Field(
        description="Narrative explaining liquidity status and coverage, accurately acknowledging if data is unavailable."
    )
    key_tradeoffs: List[str] = Field(
        default_factory=list,
        description="List of factual financial trade-offs identified from the deterministic evaluation.",
    )
    data_limitations_noted: List[str] = Field(
        default_factory=list,
        description="List of data boundaries or missing dimensions explicitly highlighted.",
    )
    provider: str = Field(
        description="The LLM provider used to generate this explanation (e.g. 'gemini', 'mock')."
    )
    model: str = Field(
        description="The specific model identifier used (e.g. 'gemini-2.5-flash', 'mock-v1')."
    )



class DecisionExplainRequest(DecisionAnalyzeRequest):
    """Request model for POST /api/financial/decision-support/explain.

    Reuses DecisionAnalyzeRequest parameters with optional LLM tuning overrides.
    """

    pass


class DecisionExplainResponse(BaseModel):
    """Unified response containing both deterministic evaluation and AI explanation."""

    deterministic_analysis: DecisionAnalyzeResponse = Field(
        description="Authoritative, deterministic financial analysis result from Phase 12 engine."
    )
    ai_explanation: Optional[AIExplanationResult] = Field(
        None,
        description="Validated AI-generated narrative explanation, or null if fallback was triggered.",
    )
    ai_status: AIExplanationStatus = Field(
        description="Operational status of the AI explanation layer."
    )
    ai_status_message: str = Field(
        description="Human-readable explanation of the AI status (e.g. success, reason for fallback)."
    )
    disclaimer: str = Field(
        default=(
            "This AI explanation translates deterministic mathematical calculations into natural language. "
            "It does not provide financial or investment advice. The deterministic backend is the sole source of truth."
        ),
        description="Standard AI decision support disclaimer.",
    )
