"""Phase 20 — Notification ORM Model.

Stores in-app notifications generated by the monitoring scheduler when new
financial insights are produced.

Security Invariants:
- user_id is a non-nullable FK to users.id — every notification is owned.
- Queries MUST always filter by user_id (IDOR protection).
- Notifications are read-only once created; only read_at may be updated.
"""

from __future__ import annotations

import uuid
from datetime import datetime, timezone
from typing import TYPE_CHECKING

from sqlalchemy import (
    Boolean,
    DateTime,
    ForeignKey,
    Index,
    String,
    Text,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base

if TYPE_CHECKING:
    from app.models.monitoring_schedule import MonitoringSchedule
    from app.models.user import User


class Notification(Base):
    """An in-app notification generated by the monitoring system.

    Notifications are linked to the schedule that triggered them.
    They carry a title, body, and an optional link to a related insight.
    Only the read/unread state may be mutated after creation.
    """

    __tablename__ = "notifications"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, default=uuid.uuid4
    )
    user_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("users.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )

    # Optional FK to the schedule that triggered this notification
    schedule_id: Mapped[uuid.UUID | None] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("monitoring_schedules.id", ondelete="SET NULL"),
        nullable=True,
    )

    # Notification type (INSIGHT_GENERATED, SCHEDULE_ERROR, etc.)
    notification_type: Mapped[str] = mapped_column(
        String(50),
        nullable=False,
        default="INSIGHT_GENERATED",
    )

    # Human-readable content
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    body: Mapped[str] = mapped_column(Text, nullable=False)

    # Read state
    is_read: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    read_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        index=True,
    )

    # Relationships
    user: Mapped["User"] = relationship("User", back_populates="notifications")
    schedule: Mapped["MonitoringSchedule | None"] = relationship(
        "MonitoringSchedule", foreign_keys=[schedule_id]
    )

    __table_args__ = (
        Index("ix_notifications_user_id", "user_id"),
        Index("ix_notifications_user_read", "user_id", "is_read"),
        Index("ix_notifications_user_created", "user_id", "created_at"),
    )

    def __repr__(self) -> str:
        return (
            f"<Notification id={self.id} type={self.notification_type} "
            f"is_read={self.is_read}>"
        )
